import { Ajv } from 'ajv';
import standaloneModule from 'ajv/dist/standalone/index.js';
import unicodeLengthModule from 'ajv/dist/runtime/ucs2length.js';
import { format } from 'prettier';
import { readFile, writeFile } from 'node:fs/promises';
import { ReadingCatalogueSchema } from '../shared/contracts.ts';
import {
  StudioConfigSchema,
  OwnerSessionSchema,
  StudioReadingPageSchema,
  StudioReadingSchema,
  PractitionerListSchema,
  AuditListSchema,
} from '../shared/studio-contracts.ts';
import type { TSchema } from 'typebox';

// Inline the pinned official helper; browsers receive no compiler or CJS require.
unicodeLengthModule.default.code = unicodeLengthModule.default.toString();
const schemas: { name: string; schema: TSchema }[] = [
  { name: 'reading-catalogue', schema: ReadingCatalogueSchema },
  { name: 'studio-config', schema: StudioConfigSchema },
  { name: 'studio-session', schema: OwnerSessionSchema },
  { name: 'studio-reading-page', schema: StudioReadingPageSchema },
  { name: 'studio-reading', schema: StudioReadingSchema },
  { name: 'studio-practitioners', schema: PractitionerListSchema },
  { name: 'studio-history', schema: AuditListSchema },
];
for (const { name, schema } of schemas) {
  const ajv = new Ajv({
    allErrors: false,
    strict: true,
    code: { source: true, esm: true },
  });
  const validate = ajv.compile(schema);
  const output = await format(
    '// Generated by npm run contracts:generate. Do not edit.\n// Includes the MIT-licensed Ajv Unicode-length helper.\n' +
      standaloneModule.default(ajv, validate),
    { parser: 'babel', singleQuote: true },
  );
  const target = new URL(
    '../shared/generated/' + name + '.js',
    import.meta.url,
  );
  if (process.argv.includes('--check')) {
    if ((await readFile(target, 'utf8')) !== output)
      throw new Error(
        'Generated contract changed: ' +
          name +
          '. Run npm run contracts:generate.',
      );
  } else await writeFile(target, output);
}
